#Uses loops to repeatedly explore Palmer Penguin statistics

#Importing the Math Module
import math

#Constant Declaration
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

valid_selections = 0

#List of Species Names
species_names = [
    SP_CHINSTRAP,
    SP_GENTOO,
    SP_ADELIE
]

#List of Species Counts
species_counts = [
    NUM_CHINSTRAP,
    NUM_GENTOO,
    NUM_ADELIE
]

#Calculating Total Species
total_species = len(species_names)

#Calculating Total Penguins
total_penguins = sum(species_counts)

#Averaging Out Penguins
average_penguins = total_penguins / total_species
average_penguins_rounded_up = math.ceil(average_penguins)

#Penguin Percentages
chinstrap_percent = (species_counts[0] / total_penguins) * 100
gentoo_percent = (species_counts[1] / total_penguins) * 100
adelie_percent = (species_counts[2] / total_penguins) * 100

#List of Species Percentages
species_percentages = [
    chinstrap_percent,
    gentoo_percent,
    adelie_percent
]

#Finding Min and Max Values
largest_count = max(species_counts)
largest_index = species_counts.index(largest_count)
largest_species = species_names[largest_index]
smallest_count = min(species_counts)
smallest_index = species_counts.index(smallest_count)
smallest_species = species_names[smallest_index]

#Output the species name with introductory text
print("Introducing the Palmer Penguins: ")
print("\n\t"+ SP_CHINSTRAP + "!")
print("\t"+ SP_GENTOO + "!")
print("and last but not least...")
print("\n\t"+ SP_ADELIE + "!")

#Display the totals
print(f"\nThere are a total of {total_species} penguin species in this data set.")
print(f"There is a total of {total_penguins} penguins in the dataset")
print(f"The average number of penguins per species is {average_penguins:.1f}.")
print(f"The average rounded up is {average_penguins_rounded_up} penguins.\n")

#Display relevant data from each species.
for index, species in enumerate(species_names):
  print(f"{species_names[index]}: {species_counts[index]} ({species_percentages[index]:.2f}%)" )

#Display Maximum and Minimum
print(f"\nThe species with the most observations is {species_names[largest_index]}"
  f" with {species_counts[largest_index]} penguins.")
print(f"The species with the least observations is {species_names[smallest_index]}"
  f" with {species_counts[smallest_index]} penguins.")

#Finding a species
print("\nExplore a species: \n Enter Chinstrap, Gentoo, Adelie, or Done:")
species_choice = input()

#The Species Choice Loop
while species_choice != "Done":
  if species_choice not in species_names:
    print(f"{species_choice} is not one of the species in the dataset.")

    species_choice = input()
  else:
    if species_choice == species_names[0]:
      selected_index = 0
    elif species_choice == species_names[1]:
      selected_index = 1
    else:
      selected_index = 2

  selected_species = species_names[selected_index]
  selected_count = species_counts[selected_index]
  selected_percent = species_percentages[selected_index]

  #Classifying a species size

  size_category = ""
  position_description = ""

  if selected_percent < 25:
    size_category = "small"
  elif selected_percent <40:
    size_category = "medium"
  else:
    size_category = "large"

  if (selected_species == largest_species) or (selected_species == smallest_species):
    if selected_species == largest_species:
      position_description = "largest"
    elif selected_species == smallest_species:
      position_description = "smallest"
  else:
    position_description = "middle-sized"

  average_position = "above" if (selected_count > average_penguins) else "below"


  #Displaying species statistics
  print(f"{selected_species} has {selected_count} observations, representing {selected_percent:.2f}% of the dataset.")
  print(f"{selected_species} is classified as the {size_category} species group.")
  print(f"{selected_species} is the {position_description} species group.")
  print(f"Its observation count is {average_position} the dataset average of {average_penguins}\n")

  #Incrementing Valid Selections
  valid_selections += 1

  #Asking for input to restart the loop
  species_choice = input()


else:
  print(f"You explored {valid_selections} valid species.\n")
  print(f"Exploration complete.")